import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { loadCatalogue } from "../src/catalogue/load.ts";
import { LICENCES } from "../src/domain/licences.ts";
import { VARIANTS } from "../src/domain/variants.ts";
import type { Catalogue } from "../src/domain/wrap.ts";

function cell(value: string): string {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/\|/g, "&#124;").replace(/[\r\n]+/g, " ").replace(/`/g, "&#96;");
}

export function renderLegalCatalogue(catalogue: Catalogue): string {
  const lines = [
    "# Legal catalogue inventory", "",
    "Generated by `npm run legal:packet` from the validated catalogue. Human review and sign-off live in [the legal packet](legal-review.md).", "",
    "| Design | Vehicle | File and SHA-256 | Output licence | Provenance |", "|---|---|---|---|---|",
  ];
  for (const wrap of catalogue.wraps) {
    const provenance = wrap.provenance.map((entry) => [
      entry.kind,
      entry.author ?? "",
      entry.sourceUrl ?? "",
      ...(entry.kind === "own" ? [entry.createdWith ?? ""] : [entry.sourceLicenceUrl ?? "", entry.retrievedOn ?? ""]),
    ].filter(Boolean).map(cell).join("; ")).join("<br>");
    lines.push(`| ${cell(wrap.title)} (${cell(wrap.id)}; added ${wrap.addedOn}) | ${cell(VARIANTS[wrap.variant].label)} | ${cell(wrap.file)}; ${wrap.width}x${wrap.height}; ${wrap.bytes} bytes; ${wrap.sha256} | ${wrap.licence} ${LICENCES[wrap.licence].url} | ${provenance} |`);
  }
  return lines.join("\n") + "\n";
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) throw new Error("usage: npm run legal:packet -- [--check]");
  const loaded = await loadCatalogue(path.resolve("content/wraps"));
  if (!loaded.ok) throw new Error("cannot generate legal inventory from an invalid catalogue");
  const rendered = renderLegalCatalogue(loaded.catalogue);
  const output = path.resolve("docs/legal-catalogue.md");
  if (args[0] === "--check") {
    if (await readFile(output, "utf8") !== rendered) throw new Error("legal inventory is stale; run npm run legal:packet");
    console.log("legal: inventory matches the validated catalogue");
  } else {
    await writeFile(output, rendered);
    console.log("legal: wrote docs/legal-catalogue.md; human sign-off was not changed");
  }
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
